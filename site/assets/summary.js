"use strict";
// Projector PR summary renderer: builds the page from summary data, embedded in
// #summary-data or fetched from data.json beside the page, then wires collapsing,
// reviewed state, highlighting, and sticky headers.
// What a summary page and the site's own pages draw alike. The site's pages load
// this script for these, as they load summary.css for its colours, and on a page
// with no summary the script draws nothing and listens for nothing.
function esc(s) {
    return (s == null ? '' : String(s)).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
}
// Projector's credit, at the foot of every page.
function creditHtml() {
    return 'Generated by <a href="https://projector.bot">Projector</a>';
}
// A moment in the reader's own time zone, to the minute.
function localTime(when) {
    return when.toLocaleString(undefined, { year: 'numeric', month: 'short', day: 'numeric', hour: 'numeric', minute: '2-digit' });
}
// A pull request's status: Merged or Closed once it is, and until then the
// verdict of the newest Projector review of its head, linked to that review,
// or Unreviewed when no Projector review names the head. Nothing when the
// build could not ask GitHub, so a status it does not know never reads as
// unreviewed.
function statusHtml(state, review) {
    if (state === 'merged')
        return '<span class="rstatus merged">Merged</span>';
    if (state === 'closed')
        return '<span class="rstatus closed">Closed</span>';
    if (review === undefined)
        return '';
    if (review.status === 'unreviewed')
        return '<span class="rstatus unreviewed">Unreviewed</span>';
    const word = review.status === 'clean' ? 'Clean' : 'Changes requested';
    return `<a class="rstatus ${review.status}" href="${esc(review.url)}" target="_blank" rel="noopener">${word}</a>`;
}
