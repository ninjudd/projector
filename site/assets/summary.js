            // always agree, a name with a letter beyond one UTF-16 unit included.
            for (const m of node.data.matchAll(IDENTIFIER)) {
                if (m.index > offset)
                    break;
                if (offset <= m.index + m[0].length)
                    return NAME.test(m[0]) ? m[0] : '';
            }
            return '';
