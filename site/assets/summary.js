        function splitLines(s) {
            const out = [], open = [];
            let cur = '';
            const re = /<span class="[^"]*">|<\/span>|\n|[^<\n]+|</g;
            let m;
            while ((m = re.exec(s)) !== null) {
                const t = m[0];
                if (t === '\n') {
                    cur += '</span>'.repeat(open.length);
                    out.push(cur);
                    cur = open.join('');
                }
                else if (t === '</span>') {
                    open.pop();
                    cur += t;
                }
                else if (t.length > 1 && t.startsWith('<')) {
                    open.push(t);
                    cur += t;
                }
                else {
                    cur += t;
                }
            }
            cur += '</span>'.repeat(open.length);
            out.push(cur);
            return out;
        }
